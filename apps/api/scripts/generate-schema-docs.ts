import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const apiDir = dirname(dirname(fileURLToPath(import.meta.url)));
const schemaDir = join(apiDir, "src/db/schema");
const markdownPath = join(apiDir, "SCHEMA.md");
const dbmlPath = join(apiDir, "schema.dbml");
const tempDir = mkdtempSync(join(tmpdir(), "tokojojo-schema-docs-"));
const tempMarkdownPath = join(tempDir, "SCHEMA.md");
const tempDbmlPath = join(tempDir, "schema.dbml");

try {
  execFileSync(
    "drizzle-docs",
    [
      "generate",
      schemaDir,
      "-d",
      "postgresql",
      "--single-file",
      "--force",
      "-o",
      tempMarkdownPath,
    ],
    { cwd: apiDir, stdio: "inherit" },
  );
  execFileSync(
    "drizzle-docs",
    [
      "generate",
      schemaDir,
      "-d",
      "postgresql",
      "-f",
      "dbml",
      "--force",
      "-o",
      tempDbmlPath,
    ],
    { cwd: apiDir, stdio: "inherit" },
  );

  const markdownHeader =
    "<!-- Generated by `pnpm --filter @tokojojo/api db:docs`; do not edit by hand. " +
    "Tables, columns, enums, relations, indexes, and PK/FK constraints come from `src/db/schema`. " +
    "CHECK constraints live in the migrations and tests; views and the append-only guard are documented in README.md. -->\n\n";
  const dbmlHeader =
    "// Generated by `pnpm --filter @tokojojo/api db:docs`; do not edit by hand.\n\n";

  writeFileSync(
    markdownPath,
    markdownHeader + readFileSync(tempMarkdownPath, "utf8"),
  );
  writeFileSync(dbmlPath, dbmlHeader + readFileSync(tempDbmlPath, "utf8"));

  execFileSync("pnpm", ["exec", "prettier", "--write", markdownPath], {
    cwd: apiDir,
    stdio: "inherit",
  });
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
