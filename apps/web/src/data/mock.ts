function toSaleItem([
  productId,
  quantity,
  discount,
  returned = 0,
]: RawSale["items"][number]): SaleItem {
  const product = products.find((item) => item.id === productId);

  if (!product) {
    throw new Error(`Unknown seed product ${productId}`);
  }

  return {
    productId,
    name: product.name,
    unit: product.unit,
    quantity,
    price: product.price,
    cost: product.cost,
    discount,
    returned,
  };
}

export const sales: Sale[] = rawSales.map((sale, index) => {
  const items = sale.items.map(toSaleItem);
  const subtotal = items.reduce(
    (total, item) => total + item.quantity * item.price,
    0,
  );
  const discount = items.reduce(
    (total, item) =>
      total + Math.max(0, item.quantity - item.returned) * item.discount,
    0,
  );

  return {
    id: `SALE-${String(index + 1).padStart(3, "0")}`,
    number: sale.number,
    time: sale.time,
    cashier: sale.cashier,
    terminal: sale.terminal,
    method: sale.method,
    status: sale.status,
    received: sale.received || subtotal - discount,
    items,
  };
});

